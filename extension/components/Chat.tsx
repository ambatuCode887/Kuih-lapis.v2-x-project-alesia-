/** A greeting that depends on the hour (night owl at 0-4), mixed with a few generic ones. */
function pickGreeting(): string {
  const hour = new Date().getHours();
  const part =
    hour < 5
      ? "night"
      : hour < 12
        ? "morning"
        : hour < 17
          ? "afternoon"
          : "evening";
  // Night greetings are never diluted, so the night-owl line always fits the hour.
  const pool =
    part === "night"
      ? TIME_GREETINGS.night!
      : [...TIME_GREETINGS[part]!, ...GENERIC_GREETINGS];
  return pool[Math.floor(Math.random() * pool.length)]!;
}

interface ChatProps {
  /** Side panel: compact, with an Expand button. Tab: wide, with a history rail. */
  layout?: "panel" | "tab";
  /** Opens the full-tab version. */
  onExpand?: () => void;
}

export default function Chat({ layout = "panel", onExpand }: ChatProps) {
  const [messages, setMessages] = useState<Message[]>([]);
  const [sessions, setSessions] = useState<ChatSession[]>([]);
  const [activeSessionId, setActiveSessionId] = useState<string | null>(null);
  const [greeting, setGreeting] = useState(pickGreeting);
  const [input, setInput] = useState("");
  const suggestions = matchSuggestions(input);
  // The history sidebar starts closed; the key is versioned so older saved choices don't override it.
  const railKey =
    layout === "panel" ? "rail-minimised-panel-v2" : "rail-minimised-v2";
  const [railMin, setRailMin] = useState(() => {
    try {
      return localStorage.getItem(railKey) !== "0";
    } catch {
      return true;
    }
  });
  function toggleRail() {
    setRailMin((current) => {
      const next = !current;
      try {
        localStorage.setItem(railKey, next ? "1" : "0");
      } catch {
        /* remembering the choice is optional */
      }
      return next;
    });
  }
  const [attachments, setAttachments] = useState<string[]>([]);
  const [notice, setNotice] = useState("");
  const [preview, setPreview] = useState<string | null>(null);
  const [loading, setLoading] = useState(false);
  const [llmUnavailable, setLlmUnavailable] = useState(false);
  const [activeAgents, setActiveAgents] = useState<string[]>([]);
  const [status, setStatus] = useState("");
  const [loaded, setLoaded] = useState(false);
  // id of an earlier check opened from Recent checks, shown on its own.
  const [focusId, setFocusId] = useState<string | null>(null);
  const [expandedSessionId, setExpandedSessionId] = useState<string | null>(null);
  const [confirmClear, setConfirmClear] = useState(false);
  const { theme, chooseTheme } = useTheme();
  // The latest awareness reminder. It stays until the user dismisses it.
  const [reminderTip, setReminderTip] = useState<ReminderTip | null>(null);
  const bottomRef = useRef<HTMLDivElement>(null);
  const inputRef = useRef<HTMLTextAreaElement>(null);
  // Speech to text: spoken words are added to whatever is already in the box.
  const speech = useSpeechInput(
    () => inputRef.current?.value ?? "",
    (text) => setInput(text),
  );
  const [dragging, setDragging] = useState(false);
  const dragDepth = useRef(0);
  const fileRef = useRef<HTMLInputElement>(null);
  const loadingRef = useRef(false);
  const abortRef = useRef<AbortController | null>(null);
  const failedLlmRequestRef = useRef<{
    text: string;
    images: string[];
  } | null>(null);
  // Set when "New check" stops a running check, so no visible stopped message is added.
  const discardStopRef = useRef(false);
  const sendTextRef = useRef(sendText);
  sendTextRef.current = sendText;

  // Show the latest awareness reminder until the user dismisses it.
  useEffect(() => {
    browser.storage.local.get(REMINDER_TIP_KEY).then((result) => {
      const saved = result[REMINDER_TIP_KEY] as ReminderTip | undefined;
      if (saved?.message) setReminderTip(saved);
    });
    const onTipChange = (
      changes: Record<string, { newValue?: unknown }>,
      area: string,
    ) => {
      if (area !== "local" || !(REMINDER_TIP_KEY in changes)) return;
      const next = changes[REMINDER_TIP_KEY]?.newValue as
        | ReminderTip
        | undefined;
      setReminderTip(next?.message ? next : null);
    };
    browser.storage.onChanged.addListener(onTipChange);
    return () => browser.storage.onChanged.removeListener(onTipChange);
  }, []);

  function dismissReminderTip() {
    setReminderTip(null);
    void browser.storage.local.remove(REMINDER_TIP_KEY);
  }

  // Load session-scoped history, migrating the pre-session message log once.
  useEffect(() => {
    Promise.all([
      browser.storage.local.get([SESSIONS_KEY, STORAGE_KEY]),
      getSessionId(),
    ]).then(([result, currentId]) => {
      const savedSessions = result[SESSIONS_KEY] as ChatSession[] | undefined;
      const saved = result[STORAGE_KEY] as Message[] | undefined;
      const migrated = saved
        ? normalizeMessages(saved.filter((message) => message.id !== "welcome"))
        : [];
      const validSessions = Array.isArray(savedSessions)
        ? savedSessions.filter((session) => session?.id && Array.isArray(session.messages))
        : [];
      const nextSessions =
        validSessions.length > 0
          ? validSessions.map((session) => ({
              ...session,
              messages: normalizeMessages(session.messages),
            }))
          : [
              {
                id: currentId,
                createdAt: Date.now(),
                messages: migrated ?? [],
              },
            ];
      const active =
        nextSessions.find((session) => session.id === currentId) ??
        nextSessions[nextSessions.length - 1]!;
      setSessions(nextSessions);
      setActiveSessionId(active.id);
      setMessages(active.messages);
      setExpandedSessionId(active.id);
      setLoaded(true);
      void browser.storage.local.set({ [SESSIONS_KEY]: nextSessions });
    });

    const onChange = (
      changes: Record<string, { newValue?: unknown }>,
      area: string,
    ) => {
      if (area === "local" && changes[SESSIONS_KEY]?.newValue) {
        const next = changes[SESSIONS_KEY].newValue as ChatSession[] | undefined;
        if (Array.isArray(next)) setSessions(next.map((session) => ({
          ...session,
          messages: normalizeMessages(session.messages),
        })));
      }
    };
    browser.storage.onChanged.addListener(onChange);
    return () => browser.storage.onChanged.removeListener(onChange);
  }, []);

  useEffect(() => {
    if (!loaded || !activeSessionId) return;
    const nextSessions = sessions.map((session) =>
      session.id === activeSessionId
        ? { ...session, messages: messages.slice(-MAX_SAVED_MESSAGES) }
        : session,
    );
    setSessions(nextSessions);
    browser.storage.local.set({ [SESSIONS_KEY]: nextSessions }).catch(() => {
      showNotice("Chat history could not be saved.");
    });
  }, [messages, loaded, activeSessionId]);

  // Handle "Check with Project Alesia" from the right-click menu.
  useEffect(() => {
    if (!loaded) return;

    async function consumePending() {
      const result = await browser.storage.local.get(PENDING_KEY);
      const pending = result[PENDING_KEY] as { prompt?: string } | undefined;
      if (!pending?.prompt) return;
      // Remove first so the other open view doesn't run it too.
      await browser.storage.local.remove(PENDING_KEY);
      sendTextRef.current(pending.prompt);
    }

    consumePending();
    const onChange = (changes: Record<string, unknown>, area: string) => {
      if (area === "local" && PENDING_KEY in changes) consumePending();
    };
    browser.storage.onChanged.addListener(onChange);
    return () => browser.storage.onChanged.removeListener(onChange);
  }, [loaded]);

  useEffect(() => {
    bottomRef.current?.scrollIntoView({ behavior: "smooth" });
  }, [messages, loading]);

  async function sendText(
    rawText: string,
    images: string[] = [],
    appendUserMessage = true,
  ) {
    const text = rawText.trim();
    if ((!text && images.length === 0) || loadingRef.current) return;

    loadingRef.current = true;
    setFocusId(null);
    setLoading(true);
    setStatus("");
    setLlmUnavailable(false);
    const controller = new AbortController();
    abortRef.current = controller;
    if (appendUserMessage) {
      setMessages((current) => [
        ...current,
        {
          id: crypto.randomUUID(),
          role: "user",
          text,
          images: images.length ? images : undefined,
        },
      ]);
    }

    const assistantId = crypto.randomUUID();
    let participatingAgents: string[] = [];

    function rememberAgent(author: string) {
      if (participatingAgents.includes(author)) return;
      participatingAgents = [...participatingAgents, author];
      setActiveAgents([...participatingAgents]);
    }

    try {
      const reply = await askAgent(
        text,
        images,
        setStatus,
        rememberAgent,
        controller.signal,
      );
      const finalMessage: Message = {
        id: assistantId,
        role: "assistant",
        text: reply.text,
        assessment: reply.assessment ?? undefined,
        sourceText: reply.assessment && text ? extractSource(text) : undefined,
        agents: reply.agents?.length ? reply.agents : participatingAgents,
        relatedQuestions: reply.relatedQuestions?.length
          ? reply.relatedQuestions
          : undefined,
      };
      setMessages((current) => [...current, finalMessage]);
      setActiveAgents([]);
    } catch (error) {
      if (isAbortError(error)) {
        if (!discardStopRef.current) {
          const stoppedMessage: Message = {
            id: assistantId,
            role: "assistant",
            text: "Stopped. No result was returned.",
            agents: participatingAgents,
          };
          setMessages((current) => [...current, stoppedMessage]);
        }
      } else if (isLlmUnavailableError(error)) {
        failedLlmRequestRef.current = { text, images };
        setLlmUnavailable(true);
      } else {
        const errorText =
          error instanceof Error ? error.message : "Something went wrong.";
        const errorMessage: Message = {
          id: assistantId,
          role: "assistant",
          text: errorText,
          agents: participatingAgents,
          isError: true,
        };
        setMessages((current) => [...current, errorMessage]);
      }
      setActiveAgents([]);
    } finally {
      abortRef.current = null;
      discardStopRef.current = false;
      loadingRef.current = false;
      setLoading(false);
      setStatus("");
    }
  }

  function stopGeneration() {
    abortRef.current?.abort();
  }

  function retryAfterLlmOutage() {
    const failedRequest = failedLlmRequestRef.current;
    setLlmUnavailable(false);
    if (failedRequest) void sendText(failedRequest.text, failedRequest.images, false);
  }

  function send() {
    speech.stop();
    const text = input;
    const images = attachments;
    setInput("");
    setAttachments([]);
    sendText(text, images);
  }

  function showNotice(message: string) {
    setNotice(message);
    window.setTimeout(() => setNotice(""), 4000);
  }

  async function addFiles(files: File[]) {
    const images = files.filter(isImageFile);
    if (images.length < files.length)
      showNotice("Only images can be attached.");
    if (images.length === 0) return;

    const room = MAX_IMAGES - attachments.length;
    if (room <= 0 || images.length > room) {
      showNotice(`You can attach up to ${MAX_IMAGES} images.`);
      if (room <= 0) return;
    }

    try {
      const prepared = await Promise.all(
        images.slice(0, room).map(prepareImage),
      );
      setAttachments((current) =>
        [...current, ...prepared].slice(0, MAX_IMAGES),
      );
    } catch (error) {
      showNotice(
        error instanceof Error ? error.message : "Could not add that image.",
      );
    }
  }

  function onPaste(event: ClipboardEvent<HTMLTextAreaElement>) {
    const files = [...event.clipboardData.items]
      .filter((item) => item.kind === "file" && item.type.startsWith("image/"))
      .flatMap((item) => {
        const file = item.getAsFile();
        return file ? [file] : [];
      });
    if (files.length === 0) return; // a plain text paste continues as normal
    event.preventDefault();
    addFiles(files);
  }

  function onDrop(event: DragEvent<HTMLFormElement>) {
    event.preventDefault();
    dragDepth.current = 0;
    setDragging(false);
    addFiles([...event.dataTransfer.files]);
  }

  // Count enter/leave pairs so moving over child elements doesn't flicker the drop zone.
  function onDragEnter(event: DragEvent<HTMLFormElement>) {
    if (![...event.dataTransfer.types].includes("Files")) return;
    dragDepth.current += 1;
    setDragging(true);
  }

  function onDragLeave() {
    dragDepth.current = Math.max(0, dragDepth.current - 1);
    if (dragDepth.current === 0) setDragging(false);
  }

  function newCheck() {
    speech.stop();
    // A check that is still running belongs to the old session, so stop it first.
    if (abortRef.current) discardStopRef.current = true;
    abortRef.current?.abort();
    setFocusId(null);
    setInput("");
    setAttachments([]);
    setGreeting(pickGreeting());
    const newId = crypto.randomUUID();
    const nextSessions = [
      ...sessions,
      { id: newId, createdAt: Date.now(), messages: [] },
    ];
    setSessions(nextSessions);
    setActiveSessionId(newId);
    setMessages([]);
    setExpandedSessionId(newId);
    void startNewSession(newId);
    void browser.storage.local.set({ [SESSIONS_KEY]: nextSessions });
    inputRef.current?.focus();
  }

  /** The only way to delete history: a deliberate, confirmed action. */
  function clearHistory() {
    setMessages([]);
    setFocusId(null);
    setConfirmClear(false);
    const freshId = crypto.randomUUID();
    const nextSessions = [{ id: freshId, createdAt: Date.now(), messages: [] }];
    setSessions(nextSessions);
    setActiveSessionId(freshId);
    setExpandedSessionId(freshId);
    void startNewSession(freshId);
    void browser.storage.local.set({ [SESSIONS_KEY]: nextSessions });
  }

  function applyQuickAction(action: QuickAction) {
    setInput(action.prompt);
    const field = inputRef.current;
    if (field) {
      field.focus();
      // Put the cursor at the end so the user can keep typing.
      requestAnimationFrame(() =>
        field.setSelectionRange(action.prompt.length, action.prompt.length),
      );
    }
  }

  // The message box grows with its text, up to a limit, then scrolls.
  useEffect(() => {
    const field = inputRef.current;
    if (!field) return;
    field.style.height = "auto";
    field.style.height = `${Math.min(field.scrollHeight, 220)}px`;
  }, [input]);

  // What is on screen: one earlier check on its own, or the active session.
  const visible = (() => {
    if (focusId) {
      const start = messages.findIndex((message) => message.id === focusId);
      if (start >= 0) {
        const reply = messages[start + 1];
        return reply?.role === "assistant"
          ? [messages[start]!, reply]
          : [messages[start]!];
      }
    }
    return messages;
  })();

  const isEmpty = visible.length === 0;

  const sessionRows = [...sessions]
    .sort((a, b) => b.createdAt - a.createdAt)
    .map((session) => {
      const sessionMessages =
        session.id === activeSessionId ? messages : session.messages;
      const checks = sessionMessages.flatMap((message, index) => {
        if (message.role !== "user") return [];
        const reply = sessionMessages[index + 1];
        const assessment =
          reply?.role === "assistant" ? reply.assessment : undefined;
        const typed = message.text.trim();
        return [{
          id: message.id,
          score: assessment ? assessment.risk_score : null,
          band: assessment
            ? riskBand(assessment.risk_level, assessment.risk_score)
            : null,
          title:
            message.title?.trim() ||
            (typed && extractSource(typed)) ||
            typed ||
            (message.images?.length ? "Screenshot" : "Check"),
        }];
      });
      const firstQuestion = sessionMessages.find((message) => message.role === "user");
      return {
        ...session,
        messages: sessionMessages,
        checks,
        title: firstQuestion?.text.trim()
          ? (extractSource(firstQuestion.text) || firstQuestion.text).slice(0, 42)
          : "New session",
      };
    });

  return (
    <div className={`app app-${layout}`}>
      <div className="glass-bg" aria-hidden="true">
        <span />
        <span />
        <span />
      </div>
      <NotificationConsentDialog />
      <DownloadWarning />
      {llmUnavailable && (
        <div className="llm-outage-overlay" role="presentation">
          <section
            aria-labelledby="llm-outage-title"
            aria-modal="true"
            className="llm-outage-dialog"
            role="alertdialog"
          >
            <div aria-hidden="true" className="llm-outage-icon">
              !
            </div>
            <h2 id="llm-outage-title">Our AI is temporarily unavailable</h2>
            <p>Gemini and the backup AI could not respond. Please try again in a few minutes.</p>
            <div className="llm-outage-actions">
              <button
                autoFocus
                className="llm-outage-retry"
                onClick={retryAfterLlmOutage}
                type="button"
              >
                Try again
              </button>
              <button className="llm-outage-close" onClick={() => setLlmUnavailable(false)} type="button">
                Close
              </button>
            </div>
          </section>
        </div>
      )}
      {(layout === "tab" || layout === "panel") && (
        <aside
          className={`rail${railMin ? " rail--min" : ""}`}
          aria-label="Chat sessions"
        >
          <div className="rail-head">
            <div className="brand">
              <Mark />
              <span className="brand-name">Project//Alesia</span>
            </div>
            <button
              type="button"
              className="ghost icon-only rail-toggle"
              onClick={toggleRail}
              aria-expanded={!railMin}
              aria-controls="rail-body"
              aria-label={
                railMin ? "Show sessions" : "Minimise sessions"
              }
              title={railMin ? "Show sessions" : "Minimise"}
            >
              <ChevronsLeftIcon
                width={20}
                height={20}
                className="rail-chevron"
              />
            </button>
          </div>
          <button
            type="button"
            className="rail-new"
            onClick={newCheck}
            aria-label="New chat"
            title="New chat"
          >
            {railMin ? (
              <PlusButtonIcon className="rail-new-img" width={26} height={26} />
            ) : (
              <PlusIcon width={16} height={16} />
            )}{" "}
            <span className="rail-new-text">New chat</span>
          </button>
          <div id="rail-body" className="rail-body" inert={railMin}>
            <div className="rail-body-inner">
              <h2 className="rail-title">Sessions</h2>
              {sessionRows.length === 0 ? (
                <p className="rail-empty">New sessions you start appear here.</p>
              ) : (
                <ul className="rail-list">
                  {sessionRows.map((session) => (
                    <li key={session.id} className="rail-session">
                      <button
                        type="button"
                        className={`rail-session-button${session.id === activeSessionId ? " is-active" : ""}`}
                        aria-expanded={expandedSessionId === session.id}
                        onClick={() => {
                          setExpandedSessionId((current) =>
                            current === session.id ? null : session.id,
                          );
                          if (session.id !== activeSessionId) {
                            setActiveSessionId(session.id);
                            setMessages(session.messages);
                            setFocusId(null);
                            void switchSession(session.id);
                          }
                        }}
                      >
                        <span className="rail-session-chevron">
                          {expandedSessionId === session.id ? "▾" : "▸"}
                        </span>
                        <span className="rail-session-title">{session.title}</span>
                        <span className="rail-session-count">{session.checks.length}</span>
                      </button>
                      {expandedSessionId === session.id && (
                        <ul className="rail-session-checks">
                          {session.checks.map((item) => (
                            <li key={item.id} className="rail-row">
                              <button
                                type="button"
                                className="rail-item"
                                aria-current={focusId === item.id ? "true" : undefined}
                                onClick={() => {
                                  if (session.id !== activeSessionId) {
                                    setActiveSessionId(session.id);
                                    setMessages(session.messages);
                                    void switchSession(session.id);
                                  }
                                  setFocusId(item.id);
                                }}
                              >
                                {item.band ? (
                                  <span className={`chip chip-${item.band.key}`}>
                                    {item.score ?? "–"}
                                  </span>
                                ) : (
                                  <span className="chip chip-question" title="Question">Q</span>
                                )}
                                <span className="rail-item-text">{item.title}</span>
                              </button>
                            </li>
                          ))}
                          {session.checks.length === 0 && (
                            <li className="rail-session-empty">No checks yet</li>
                          )}
                        </ul>
                      )}
                    </li>
                  ))}
                </ul>
              )}
              {sessionRows.length > 0 &&
                (confirmClear ? (
                  <div
                    className="rail-confirm"
                    role="group"
                    aria-label="Confirm clearing history"
                  >
                    <p>Delete all recent checks?</p>
                    <button
                      type="button"
                      className="rail-danger"
                      onClick={clearHistory}
                    >
                      Yes, delete
                    </button>
                    <button
                      type="button"
                      className="ghost"
                      onClick={() => setConfirmClear(false)}
                    >
                      Keep them
                    </button>
                  </div>
                ) : (
                  <button
                    type="button"
                    className="rail-clear"
                    onClick={() => setConfirmClear(true)}
                  >
                    Clear history
                  </button>
                ))}
            </div>
          </div>
          <div className="settings-dock">
            <SettingsMenu theme={theme} onChangeTheme={chooseTheme} />
          </div>
        </aside>
      )}

      <div className={`chat${isEmpty && !loading ? " chat--start" : ""}`}>
        {layout === "panel" && (
          <header className="bar">
            <div className="brand">
              <Mark />
              <span className="brand-name">Project//Alesia</span>
            </div>
            <div className="bar-actions">
              {onExpand && (
                <button
                  type="button"
                  className="ghost icon-only"
                  onClick={onExpand}
                  aria-label="Open in a full tab"
                  title="Open in a full tab"
                >
                  <ExpandIcon width={16} height={16} />
                </button>
              )}
            </div>
          </header>
        )}

        <div className="scroll">
          <div className="thread">
            {isEmpty && !loading && (
              <section className="welcome">
                <div className="welcome-hero">
                  <h1 className="welcome-title">{greeting}</h1>
                  <p className="welcome-lead">
                    Paste a message, link or screenshot. I&apos;ll tell you if
                    it looks like a scam.
                  </p>
                </div>
              </section>
            )}

            {focusId && (
              <div className="viewing" role="status">
                <span>You are looking at an earlier check.</span>
                <button
                  type="button"
                  className="ghost"
                  onClick={() => setFocusId(null)}
                >
                  Back to current chat
                </button>
              </div>
            )}

            {visible.map((message) => (
              <div key={message.id} id={`msg-${message.id}`} className="turn">
                {message.assessment && (
                  <VerdictSlip
                    assessment={message.assessment}
                    sourceText={message.sourceText}
                  />
                )}
                {message.role === "user" ? (
                  <>
                    {message.images && message.images.length > 0 && (
                      <div className="sent-images">
                        {message.images.map((src, index) => (
                          <button
                            key={index}
                            type="button"
                            className="sent-image"
                            onClick={() => setPreview(src)}
                            aria-label="View image full size"
                          >
                            <img
                              src={src}
                              alt={`Screenshot ${index + 1} you sent`}
                            />
                          </button>
                        ))}
                      </div>
                    )}
                    {message.text && <div className="said">{message.text}</div>}
                  </>
                ) : message.isError ? (
                  <div className="reply reply-error">{message.text}</div>
                ) : message.assessment ? (
                  <div className="reply expanded-explanation">
                    <Markdown>{message.text}</Markdown>
                  </div>
                ) : (
                  <div className="reply">
                    <Markdown>{message.text}</Markdown>
                  </div>
                )}
                {message.role === "assistant" &&
                  !!message.relatedQuestions?.length && (
                    <div
                      className="related-questions"
                      aria-label="Related questions"
                    >
                      <span className="related-questions-label">
                        Related questions
                      </span>
                      {message.relatedQuestions.map((question) => (
                        <button
                          key={question}
                          type="button"
                          className="related-question"
                          disabled={loading}
                          onClick={() => sendText(question)}
                        >
                          {question}
                        </button>
                      ))}
                    </div>
                  )}
                {message.role === "assistant" && !!message.agents?.length && (
                  <div
                    className="agent-trace"
                    aria-label="Agents that participated"
                  >
                    <span className="agent-trace-label">Agents</span>
                    <span className="agent-trace-names">
                      {message.agents.join(" → ")}
                    </span>
                  </div>
                )}
              </div>
            ))}

            {loading && activeAgents.length > 0 && (
              <div
                className="agent-trace"
                aria-label="Agents working on this response"
              >
                <span className="agent-trace-label">Agents</span>
                <span className="agent-trace-names">
                  {activeAgents.join(" → ")}
                </span>
              </div>
            )}

            {loading && (
              <div className="working" role="status">
                <ShieldScan size={22} />
                {status || "Analyzing context…"}
              </div>
            )}
            <div ref={bottomRef} />
          </div>
        </div>

        {notice && (
          <p className="notice" role="status">
            {notice}
          </p>
        )}

        {speech.supported && (speech.listening || speech.problem) && (
          <div className={`mic-status${speech.problem ? " has-problem" : ""}`} role="status" aria-live="polite">
            {speech.problem ? (
              <>
                <span>{SPEECH_PROBLEM_TEXT[speech.problem]}</span>
                {speech.problem === "blocked" && onExpand && (
                  <button type="button" className="mic-status-btn" onClick={onExpand}>
                    Open in a full tab
                  </button>
                )}
                <button type="button" className="mic-status-btn" onClick={speech.clearProblem}>
                  Dismiss
                </button>
              </>
            ) : (
              <>
                <span className="mic-dot" aria-hidden="true" />
                <span>
                  Listening in {SPEECH_LANGUAGES.find((item) => item.value === speech.lang)?.label}…
                </span>
                {SPEECH_LANGUAGES.filter((item) => item.value !== speech.lang).map((item) => (
                  <button
                    key={item.value}
                    type="button"
                    className="mic-status-btn mic-status-switch"
                    onClick={() => speech.setLang(item.value)}
                  >
                    Switch to {item.label}
                  </button>
                ))}
                <button type="button" className="mic-status-btn mic-status-stop" onClick={speech.stop}>
                  Stop
                </button>
              </>
            )}
          </div>
        )}

        <form
          className={`composer is-start${dragging ? " is-dragging" : ""}`}
          onSubmit={(event) => {
            event.preventDefault();
            send();
          }}
          onDragOver={(event) => event.preventDefault()}
          onDragEnter={onDragEnter}
          onDragLeave={onDragLeave}
          onDrop={onDrop}
        >
          {dragging && (
            <div className="drop-zone" aria-hidden="true">
              <PaperclipIcon width={26} height={26} />
              <span>Drop your screenshot here</span>
            </div>
          )}
          {attachments.length > 0 && (
            <ul className="attachments" aria-label="Images ready to send">
              {attachments.map((src, index) => (
                <li key={index} className="attachment">
                  <button
                    type="button"
                    className="attachment-thumb"
                    onClick={() => setPreview(src)}
                    aria-label={`Preview image ${index + 1}`}
                  >
                    <img src={src} alt={`Image ${index + 1} ready to send`} />
                  </button>
                  <button
                    type="button"
                    className="attachment-remove"
                    onClick={() =>
                      setAttachments((current) =>
                        current.filter((_, i) => i !== index),
                      )
                    }
                    aria-label={`Remove image ${index + 1}`}
                  >
                    <CloseIcon width={12} height={12} />
                  </button>
                </li>
              ))}
            </ul>
          )}
          {suggestions.length > 0 && (
            <ul className="suggest-chips" aria-label="Suggested checks">
              {suggestions.map((question) => (
                <li key={question}>
                  <button
                    type="button"
                    className="suggest-chip"
                    onClick={() => {
                      setInput(question);
                      inputRef.current?.focus();
                    }}
                  >
                    {question}
                  </button>
                </li>
              ))}
            </ul>
          )}
          <div className="composer-row">
            <button
              type="button"
              className="attach"
              onClick={() => fileRef.current?.click()}
              aria-label="Add a photo"
              title="Add a photo or screenshot"
            >
              <PaperclipIcon width={22} height={22} />
              <span>Photo</span>
            </button>
            {speech.supported && (
              <button
                type="button"
                className={`mic${speech.listening ? " is-listening" : ""}`}
                onClick={speech.toggle}
                aria-pressed={speech.listening}
                aria-label={speech.listening ? "Stop dictating" : "Dictate"}
                title={speech.listening ? "Stop dictating" : "Dictate"}
              >
                <MicIcon width={22} height={22} />
              </button>
            )}
            <input
              ref={fileRef}
              type="file"
              accept="image/*"
              multiple
              hidden
              onChange={(event) => {
                addFiles([...(event.target.files ?? [])]);
                event.target.value = "";
              }}
            />
            <textarea
              ref={inputRef}
              value={input}
              placeholder="Ask Alesia…"
              rows={1}
              aria-label="Message"
              onChange={(event) => setInput(event.target.value)}
              onPaste={onPaste}
              onKeyDown={(event) => {
                if (event.key === "Enter" && !event.shiftKey) {
                  event.preventDefault();
                  send();
                }
              }}
            />
            {loading ? (
              <button
                type="button"
                className="send is-stop"
                onClick={stopGeneration}
                aria-label="Stop"
                title="Stop this check"
              >
                <StopIcon width={22} height={22} />
                <span>Stop</span>
              </button>
            ) : (
              <button
                type="submit"
                className="send"
                disabled={!input.trim() && attachments.length === 0}
                aria-label="Check"
              >
                <SendIcon width={22} height={22} />
                <span>Check</span>
              </button>
            )}
          </div>
        </form>
        {isEmpty && !loading && (
          <ul className="quick-lines" aria-label="Start a check">
            {QUICK_ACTIONS.map((action) => (
              <li key={action.title}>
                <button
                  type="button"
                  className="quick-line hover-tint"
                  style={{ ["--tint" as string]: action.tint }}
                  onClick={() => applyQuickAction(action)}
                >
                  <span className="quick-line-icon">
                    <action.icon width={20} height={20} />
                  </span>
                  <span className="quick-line-title">{action.title}</span>
                  <span className="quick-line-text">{action.description}</span>
                  <ArrowIcon
                    width={16}
                    height={16}
                    className="quick-line-arrow"
                  />
                </button>
              </li>
            ))}
          </ul>
        )}
        {(!isEmpty || loading) && (
          <p className="ai-note" role="note">
            Project Alesia can make mistakes. Check important info.
          </p>
        )}
      </div>
      {reminderTip && (
        <div className="reminder-toast" role="status" aria-live="polite">
          <button
            type="button"
            className="reminder-toast-x"
            onClick={dismissReminderTip}
            aria-label="Close this tip"
            title="Close"
          >
            <CloseIcon width={16} height={16} />
          </button>
          <span className="reminder-toast-title">Awareness tip</span>
          <p className="reminder-toast-text">{reminderTip.message}</p>
          <button
            type="button"
            className="ghost reminder-toast-close"
            onClick={dismissReminderTip}
          >
            Got it
          </button>
        </div>
      )}
      {preview && <Lightbox src={preview} onClose={() => setPreview(null)} />}
    </div>
  );
}
