interface ChatSession {
  id: string;
  createdAt: number;
  messages: Message[];
}

function normalizeMessages(messages: Message[]): Message[] {
  return messages.map((message) => ({
    ...message,
    assessment: message.assessment
      ? (parseAssessment(JSON.stringify(message.assessment)) ?? undefined)
      : undefined,
  }));
}

